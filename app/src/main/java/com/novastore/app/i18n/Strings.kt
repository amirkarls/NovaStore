    fun get(lang: String, key: String): String {
        return when (lang) {
            "en" -> en[key] ?: ru[key] ?: key
            "uk" -> uk[key] ?: ru[key] ?: key
            "kk" -> kk[key] ?: ru[key] ?: key
            "es" -> es[key] ?: ru[key] ?: key
            else -> ru[key] ?: key
        }
    }

    fun needsWarning(lang: String): Boolean {
        return lang == "uk" || lang == "kk" || lang == "es"
    }
